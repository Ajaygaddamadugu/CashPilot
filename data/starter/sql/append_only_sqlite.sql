-- SQLite triggers that make history append-only: rows can be inserted, never changed or deleted.
-- Status changes are new rows in the *_event / cf_revision tables.

CREATE TRIGGER receivable_no_update BEFORE UPDATE ON receivable
BEGIN SELECT RAISE(ABORT, 'receivable is append-only'); END;
CREATE TRIGGER receivable_no_delete BEFORE DELETE ON receivable
BEGIN SELECT RAISE(ABORT, 'receivable is append-only'); END;
